"""Числа словами в голосовых командах: «две минуты сорок секунд» → «2 минуты 40 секунд»."""

import re

_VALUES = {
    "ноль": 0, "один": 1, "одна": 1, "одну": 1, "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5,
    "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10, "одиннадцать": 11, "двенадцать": 12,
    "тринадцать": 13, "четырнадцать": 14, "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17,
    "восемнадцать": 18, "девятнадцать": 19, "двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50,
    "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80, "девяносто": 90, "сто": 100,
}
_NUMBER = re.compile(r"(?<![а-яё])(?:" + "|".join(sorted(_VALUES, key=len, reverse=True))
                     + r")(?:\s+(?:" + "|".join(sorted(_VALUES, key=len, reverse=True)) + r"))*(?![а-яё])",
                     re.IGNORECASE)


_STEP = re.compile(r"(?:музык\w*|громкост\w*|звук\w*|компьютер\w*|тише|громче|потише|погромче|убавь|прибавь"
                   r"|приглуши|подними|опусти|уменьши|увеличь)\s+на\s+(\d{1,3})\b", re.IGNORECASE)


def volume_step(text: str) -> str:
    """Шаг громкости из фразы: «убавь музыку на 20» → «20». Число должно стоять сразу за словом о
    громкости: в «приглуши музыку и нагрей чай на 85» 85 относится к чайнику."""
    m = _STEP.search(digits_in(text))
    return str(min(100, int(m.group(1)))) if m else ""


def digits_in(text: str) -> str:
    """Заменить числа словами на цифры, остальной текст не трогать."""
    t = re.sub(r"\bполторы\s+минуты\b", "90 секунд", text or "", flags=re.IGNORECASE)
    t = re.sub(r"\bпол\s*минуты\b", "30 секунд", t, flags=re.IGNORECASE)
    return _NUMBER.sub(lambda m: str(sum(_VALUES[w] for w in m.group(0).lower().split())), t)
